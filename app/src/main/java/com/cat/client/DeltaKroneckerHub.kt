    fun byKind(kind: Kind): List<Feed> = FEEDS.filter { it.kind == kind }

    private val BRIDGE_TRANSPORTS = listOf("obfs4 ", "webtunnel ", "snowflake ", "meek_lite ", "meek ", "conjure ")

    /**
     * Bridge lines from a collector file: «Bridge » prefixes removed, comments/blank lines skipped, only known
     * pluggable transports (a vanilla «IP:port FP» line is accepted too), duplicates dropped, at most [max].
     */
    fun parseBridgeLines(text: String, max: Int = 10): List<String> {
        val out = LinkedHashSet<String>()
        for (raw in text.lineSequence()) {
            var line = raw.trim()
            if (line.isEmpty() || line.startsWith("#") || line.startsWith("//")) continue
            if (line.startsWith("Bridge ", ignoreCase = true)) line = line.substring(7).trim()
            val known = BRIDGE_TRANSPORTS.any { line.startsWith(it, ignoreCase = true) }
            val vanilla = Regex("^\\[?[0-9a-fA-F:.]+]?:\\d{1,5} [0-9A-Fa-f]{40}$").matches(line)
            if (!known && !vanilla) continue
            out += line.replace(Regex("\\s+"), " ")
            if (out.size >= max) break
        }
        return out.toList()
    }
