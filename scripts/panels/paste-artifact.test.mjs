/**
 * PASTE ARTIFACT — what the app's «copy Worker code» button actually hands over.
 *
 * The button used to copy the ~1.2 MB obfuscated bundle that the app uploads over
 * the API. That is the wrong file for a human: the owner pastes it into the
 * Cloudflare editor by hand, and a 1.2 MB string is one interrupted clipboard
 * operation away from a truncated Worker — which answers Cloudflare's
 * «Error 1101» for every request (see the README section of the same name). The
 * official paste artifact is the 3-line `catpanel.min.js` (~474 KB).
 *
 * Three things have to stay true, and none of them is visible at runtime:
 *   1. the asset inside the APK is byte-identical to `dist-panel/catpanel.min.js`
 *      (both are regenerated by CI — a stale copy would hand out an old panel);
 *   2. it keeps the shape a paste can be checked against (marker line, 3 lines,
 *      the end-of-file signature) and the same version as the worker source;
 *   3. the Kotlin side sorts the files the right way round: paste asset first,
 *      the big bundle only as an announced fallback.
 *
 * Run standalone:  node scripts/panels/paste-artifact.test.mjs
 */
import { strict as assert } from 'node:assert';
import { readFileSync, statSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = new URL('../../', import.meta.url);
const assetPath = new URL('app/src/main/assets/panels/catpanel.min.js', root);
const distPath = new URL('dist-panel/catpanel.min.js', root);
const sourcePath = new URL('app/src/main/assets/panels/catclient.worker.js', root);

let pass = 0; let fail = 0;
const ok = (name, cond, extra) => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra !== undefined ? '  → ' + extra : '')); }
};

console.log('\nPaste artifact — the file the clipboard is supposed to carry\n');

const asset = readFileSync(assetPath);
const dist = readFileSync(distPath);
const source = readFileSync(sourcePath, 'utf8');

/* ---------- 1) one file, two locations, no drift ---------- */
{
  ok('the APK asset exists', asset.length > 0, asset.length);
  ok('…and is byte-identical to dist-panel/catpanel.min.js (CI regenerates both)',
    asset.equals(dist),
    asset.length + ' vs ' + dist.length);
  // Both are rebuilt by the same CI run; equality is the only thing that stops
  // the APK from shipping a panel version nobody deploys any more.
  const apkMtime = statSync(assetPath).mtimeMs;
  ok('…and the two copies are not accidentally the same file', typeof apkMtime === 'number');
}

/* ---------- 2) the shape a manual paste is verified against ---------- */
{
  const text = asset.toString('utf8');
  const lines = text.split('\n');
  ok('3 lines (marker · paste instruction · the whole code)', lines.length === 3, lines.length);
  const marker = text.match(/^\/\* CAT_PANEL_VERSION = '([0-9]+(?:\.[0-9]+)+)' \*\//);
  ok('line 1 is the version marker', !!marker, JSON.stringify(text.slice(0, 44)));
  ok('the code ends with a closing statement, not mid-token', text.trimEnd().endsWith('};'), JSON.stringify(text.trimEnd().slice(-24)));

  const sourceVersion = source.match(/CAT_PANEL_VERSION = '([0-9]+(?:\.[0-9]+)+)'/)?.[1];
  ok('the asset declares the same version as the worker source',
    !!marker && marker[1] === sourceVersion, marker && marker[1] + ' vs ' + sourceVersion);

  ok('raw size is in the paste range (300–600 KB)', asset.length >= 300_000 && asset.length <= 600_000, asset.length);
  const gz = gzipSync(asset, { level: 9 }).length;
  ok('gzip stays under the 140 KB warning line', gz < 140_000, gz);
  // The panel UI is Persian, so the file is UTF-8 and NOT ASCII: what matters is
  // that it survives the Android asset → String → clipboard round-trip byte for
  // byte (bufferedReader() decodes UTF-8, ClipData stores UTF-16).
  ok('UTF-8 round-trips without losing a character',
    Buffer.from(text, 'utf8').equals(asset) && !text.includes('\uFFFD'));
}

/* ---------- 3) the Kotlin side prefers it, announces the fallback ---------- */
{
  const workerKt = readFileSync(new URL('app/src/main/java/com/cat/client/CloudflareWorker.kt', root), 'utf8');
  const activityKt = readFileSync(new URL('app/src/main/java/com/cat/client/MainActivity.kt', root), 'utf8');

  ok('CloudflareWorker points the paste asset at panels/catpanel.min.js',
    /PASTE_ASSET_PATH\s*=\s*"panels\/catpanel\.min\.js"/.test(workerKt));
  ok('…and reads it with a size+marker gate before anything is copied',
    /fun builtInPasteScript\(/.test(workerKt) && /fun pasteScriptIsSane\(/.test(workerKt) &&
      /PASTE_MIN_CHARS/.test(workerKt) && /contains\(PASTE_VERSION_MARKER\)/.test(workerKt));
  ok('the copy button uses the paste artifact', /copyPanelPasteCode\(\)/.test(activityKt));
  ok('…with the big bundle only as a fallback',
    /builtInPasteScript\(this\)[\s\S]{0,400}builtInWorkerScript\(this\)/.test(activityKt));
  ok('…and the fallback is announced, not silent',
    /cloud_code_copied_large/.test(activityKt));
  // The API upload path is the opposite case: it must keep sending the obfuscated
  // bundle (the app's own anti-1101 rule refuses the readable min — READABLE_SIGNATURES).
  const deployBody = workerKt.slice(
    workerKt.indexOf('suspend fun deployBuiltIn('),
    workerKt.indexOf('sealed class PanelUpdateOutcome'),
  );
  ok('…and that function was actually found in the source', deployBody.length > 1_000, deployBody.length);
  ok('the in-app API deploy still uploads the obfuscated bundle (never the paste file)',
    deployBody.includes('builtInWorkerScript(context)') && !deployBody.includes('builtInPasteScript'),
    deployBody.length + ' chars');
}

/* ---------- 4) CI keeps the two copies in lockstep ---------- */
{
  const yml = readFileSync(new URL('.github/workflows/android.yml', root), 'utf8');
  ok('the Android build copies the freshly built min into the APK assets',
    /cp dist-panel\/catpanel\.min\.js app\/src\/main\/assets\/panels\/catpanel\.min\.js/.test(yml));
  ok('…and commits it with the other snapshots',
    /git add [^\n]*app\/src\/main\/assets\/panels\/catpanel\.min\.js/.test(yml));
  ok('…right after the minify step, i.e. before the in-place obfuscation',
    yml.indexOf('cp dist-panel/catpanel.min.js') > yml.indexOf('minify.mjs') &&
      yml.indexOf('cp dist-panel/catpanel.min.js') < yml.indexOf('obfuscate.mjs app/src/main/assets/panels/catclient.worker.js app/src/main/assets/panels/catclient.worker.js'));
}

console.log('\npaste artifact: ' + pass + ' passed, ' + fail + ' FAILED');
assert.equal(fail, 0, fail + ' checks failed');
